export function getChapterBySlug(slug) {
  return CHAPTERS.find((chapter) => chapter.slug === slug)
}

export function getVisualization(slug, visualizationId) {
  const chapter = getChapterBySlug(slug)
  if (!chapter) return { chapter: undefined, visualization: undefined }
  const visualization = chapter.visualizations.find((v) => v.id === visualizationId)
  return { chapter, visualization }
}

export function chaptersByPaper(paper) {
  return CHAPTERS.filter((chapter) => chapter.paper === paper)
}
